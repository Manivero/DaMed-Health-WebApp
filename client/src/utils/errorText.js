// Ошибка формы хранится либо как готовый текст с сервера (показывается как есть — серверные тексты пока
// не локализуются, TD-023), либо как { key } ключа словаря: тогда перевод делается ПРИ ОТРИСОВКЕ и меняет
// язык вместе с интерфейсом (строка, переведённая заранее, осталась бы на старом языке после переключения).
export const errorText = (error, t) =>
  error && typeof error === "object" && error.key ? t(error.key) : error;
